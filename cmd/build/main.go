// Command build builds the module programs and the application.
//
// Run it from the repository root:
//
//	go run ./cmd/build [flags]
//
// It builds every modules/<id> into build/bin/modules/<id>.vfgmod, writes
// the installer's module sections (build/windows/installer/modules.nsh)
// from their --info, and then runs "wails build", with -nsis unless
// -nsis=false.
package main

import (
	"context"
	"flag"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"time"

	"VRCFaceTracking/internal/metadata"
	"VRCFaceTracking/internal/module/manager"
	"VRCFaceTracking/internal/module/plugin"
)

const (
	modulesDir    = "modules"
	moduleOutDir  = "build/bin/modules"
	moduleExt     = ".vfgmod"
	nsisInclude   = "build/windows/installer/modules.nsh"
	infoTimeout   = 10 * time.Second
	metadataFile  = "wails.json"
	moduleLDFlags = "-s -w"
)

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "Error:", err)
		os.Exit(1)
	}
}

func run() error {
	app := flag.Bool("app", true, "build the application with wails after the modules")
	nsis := flag.Bool("nsis", true, "also build the NSIS installer (needs -app)")
	install := flag.Bool("install", false, "copy the built modules into the current user's module folder")
	flag.Parse()

	raw, err := os.ReadFile(metadataFile)
	if err != nil {
		return fmt.Errorf("run from the repository root: %w", err)
	}
	metadata.Init(raw)

	modules, err := buildModules(context.Background())
	if err != nil {
		return err
	}
	if *install {
		if err := installModules(modules); err != nil {
			return err
		}
	}
	if !*app {
		return nil
	}
	args := []string{"build"}
	if *nsis {
		if err := writeNSISInclude(modules); err != nil {
			return err
		}
		args = append(args, "-nsis")
	}
	return runCmd("wails", args...)
}

// module is one built module program.
type module struct {
	path string
	desc plugin.Description
}

// buildModules builds every modules/<id> that is a main package and reads
// the description of the result.
func buildModules(ctx context.Context) ([]module, error) {
	entries, err := os.ReadDir(modulesDir)
	if err != nil {
		return nil, err
	}
	var built []module
	for _, e := range entries {
		if !e.IsDir() {
			continue
		}
		id := e.Name()
		if _, err := os.Stat(filepath.Join(modulesDir, id, "main.go")); err != nil {
			continue
		}
		out := filepath.Join(moduleOutDir, id+moduleExt)
		fmt.Printf("Building module %s -> %s\n", id, out)
		if err := runCmd("go", "build", "-ldflags="+moduleLDFlags, "-o", out, "./"+modulesDir+"/"+id); err != nil {
			return nil, fmt.Errorf("build module %s: %w", id, err)
		}
		desc, err := readInfo(ctx, out)
		if err != nil {
			return nil, fmt.Errorf("module %s: %w", id, err)
		}
		// The host names installed programs <id>.vfgmod, so a mismatch
		// would install the module under a different name.
		if desc.ID != id {
			return nil, fmt.Errorf("module in %s/%s reports ID %q", modulesDir, id, desc.ID)
		}
		built = append(built, module{path: out, desc: desc})
	}
	if len(built) == 0 {
		return nil, fmt.Errorf("no modules found in %s", modulesDir)
	}
	return built, nil
}

func readInfo(ctx context.Context, path string) (plugin.Description, error) {
	ctx, cancel := context.WithTimeout(ctx, infoTimeout)
	defer cancel()
	abs, err := filepath.Abs(path)
	if err != nil {
		return plugin.Description{}, err
	}
	return plugin.ReadInfo(ctx, abs)
}

// installModules copies the modules to where the application looks for
// them. The application must not be running.
func installModules(modules []module) error {
	dataDir, err := metadata.Info.PersistentDataDir()
	if err != nil {
		return err
	}
	dir := manager.DefaultDir(dataDir)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	for _, m := range modules {
		dst := filepath.Join(dir, m.desc.ID+moduleExt)
		fmt.Printf("Installing module %s -> %s\n", m.desc.ID, dst)
		data, err := os.ReadFile(m.path)
		if err != nil {
			return err
		}
		if err := os.WriteFile(dst, data, 0o755); err != nil {
			return fmt.Errorf("install module %s (is the application running?): %w", m.desc.ID, err)
		}
	}
	return nil
}

// nsisString escapes s for a double quoted NSIS string.
var nsisString = strings.NewReplacer(`$`, `$$`, `"`, `$\"`, "\r", "", "\n", `$\n`)

// writeNSISInclude writes the installer sections and component page
// descriptions for the modules; project.nsi includes the file.
func writeNSISInclude(modules []module) error {
	var b strings.Builder
	b.WriteString("; Generated by cmd/build. Do not edit.\n\n")
	b.WriteString("!macro moduleSections\n")
	for _, m := range modules {
		fmt.Fprintf(&b, "    Section \"%s\" %s\n", nsisString.Replace(m.desc.Metadata.Name), sectionID(m.desc.ID))
		fmt.Fprintf(&b, "        !insertmacro installModule \"%s\"\n", m.desc.ID)
		b.WriteString("    SectionEnd\n")
	}
	b.WriteString("!macroend\n\n")
	b.WriteString("!macro moduleDescriptions\n")
	for _, m := range modules {
		fmt.Fprintf(&b, "    !insertmacro MUI_DESCRIPTION_TEXT ${%s} \"%s\"\n", sectionID(m.desc.ID), nsisString.Replace(m.desc.Metadata.Description))
	}
	b.WriteString("!macroend\n")
	return os.WriteFile(nsisInclude, []byte(b.String()), 0o644)
}

// sectionID turns a module ID into an NSIS section index name, which may
// only contain letters, digits and underscores.
func sectionID(id string) string {
	return "SecMod_" + strings.Map(func(r rune) rune {
		if r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || r >= '0' && r <= '9' {
			return r
		}
		return '_'
	}, id)
}

func runCmd(name string, args ...string) error {
	cmd := exec.Command(name, args...)
	cmd.Stdout = os.Stdout
	cmd.Stderr = os.Stderr
	return cmd.Run()
}
